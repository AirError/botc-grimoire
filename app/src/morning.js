const MORNING_COUNT = { 3: ['трое', 'троих'], 4: ['четверо', 'четверых'], 5: ['пятеро', 'пятерых'], 6: ['шестеро', 'шестерых'],
  7: ['семеро', 'семерых'], 8: ['восьмеро', 'восьмерых'], 9: ['девятеро', 'девятерых'], 10: ['десятеро', 'десятерых'] };

const morningJoin = names => names.length < 2 ? (names[0] || '') : names.slice(0, -1).join(', ') + ' и ' + names[names.length - 1];
const morningKind = (n, first) => n === 0 ? (first ? 'first' : 'none') : n === 1 ? 'one' : n === 2 ? 'two' : 'many';

// names — имена умерших (можно уже с разметкой); k — номер варианта (любое целое, берётся по кругу)
function morningText(names, first, k) {
  const list = MORNING[morningKind(names.length, first)], i = ((k % list.length) + list.length) % list.length;
  const cnt = MORNING_COUNT[names.length] || [String(names.length), String(names.length)];
  const text = list[i].replace('{names}', morningJoin(names)).replace('{count}', cnt[0]).replace('{countAcc}', cnt[1]);
  return { text, i, total: list.length };
}
